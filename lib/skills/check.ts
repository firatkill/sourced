type Schema = {
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  additionalProperties?: Schema | boolean;
  anyOf?: Schema[];
  oneOf?: Schema[];
};
export type Field = { path: string; type: string; optional: boolean };

/** JSON Schema is Zod's public introspection API; unions retain all branch fields. */
export function schemaFields(schema: z.ZodType, root = 'result'): Field[] {
  const fields = new Map<string, Field>();
  function walk(node: Schema, path: string, optional: boolean) {
    const variants = node.anyOf ?? node.oneOf;
    if (variants) {
      for (const variant of variants) walk(variant, path, optional);
      for (const key of new Set(
        variants.flatMap((variant) => Object.keys(variant.properties ?? {})),
      )) {
        const field = fields.get(`${path}.${key}`);
        if (field && variants.some((variant) => !variant.required?.includes(key)))
          field.optional = true;
      }
      return;
    }
    const type = node.enum
      ? node.enum.map((value) => JSON.stringify(value)).join(' | ')
      : node.const !== undefined
        ? JSON.stringify(node.const)
        : Array.isArray(node.type)
          ? node.type.join(' | ')
          : (node.type ?? 'unknown');
    const previous = fields.get(path);
    fields.set(path, {
      path,
      type: [...new Set([...(previous?.type.split(' | ') ?? []), ...type.split(' | ')])].join(
        ' | ',
      ),
      optional: optional || (previous?.optional ?? false),
    });
    for (const [key, child] of Object.entries(node.properties ?? {})) {
      walk(child, `${path}.${key}`, !node.required?.includes(key));
    }
    if (node.items) walk(node.items, `${path}[]`, false);
    if (typeof node.additionalProperties === 'object') {
      walk(node.additionalProperties, `${path}[key]`, false);
    }
  }
  walk(
    z.toJSONSchema(schema, { unrepresentable: 'any' }) as Schema,
    root,
    schema.safeParse(undefined).success,
  );
  return [...fields.values()].sort((a, b) => a.path.localeCompare(b.path, 'en'));
}

const exits: Record<ExitCode, string> = {
  0: 'ok',
  1: 'failure',
  2: 'user action needed (NEEDS_CONFIRMATION, CHECKS_FAILED, missing key, CORPUS_MISMATCH, CORPUS_EMPTY, robots refusal)',
  130: 'interrupted',
};
const globalFlags =
  helpText()
    .split('\n')
    .find((line) => line.startsWith('Global flags:'))
    ?.match(/--[\w-]+/g) ?? [];
const names = Object.keys(commands) as Command[];
export const referencePath = '.agents/skills/_shared/cli-reference.md';
function fieldLines(schema: z.ZodType, root?: string): string[] {
  return schemaFields(schema, root).map(
    (field) => `- \`${field.path}\`: ${field.type}${field.optional ? ' (optional)' : ''}`,
  );
}
export function generateReference(): string {
  const errorExports: Record<string, unknown> = errors;
  return [
    '# CLI reference',
    '',
    'Generated by `pnpm check-skills --write`. Do not edit by hand.',
    '',
    'Convention: before referencing result paths, put `<!-- sourced-command: doctor -->` on its own line (replace doctor with the exact command name). It applies until the next such marker. Every result path requires a marker; command examples do not change it. Use literal JSON paths such as `result.checks[].ok`. `[key]` denotes a record key; optional marks a property that may be absent from its parent. Union paths include every variant. Standalone flags use the marker command when present, otherwise the full registry. Upper-snake words are checked as error codes.',
    '',
    '## Commands and global flags',
    '',
    '```text',
    helpText()
      .split('\n')
      .map((line) => line.trimEnd())
      .join('\n'),
    '```',
    '',
    '## JSON envelope',
    '',
    ...fieldLines(CliEnvelope, '$'),
    '',
    '## Exit codes',
    '',
    ...Object.entries(exits).map(([code, meaning]) => `- \`${code}\`: ${meaning}`),
    ...names.flatMap((name) => ['', `## ${name} result`, '', ...fieldLines(commandSchemas[name])]),
    '',
    '## Error codes',
    '',
    ...errors.ERROR_CODES.map((code) => {
      const meaning = errorExports[`${code}_MESSAGE`];
      return `- \`${code}\`${typeof meaning === 'string' ? `: ${meaning}` : ''}`;
    }),
    '',
  ].join('\n');
}
/** Read declarations, never runtime environment values or .env.local. */
export function knownSkillWords(): Set<string> {
  const words = new Set<string>(errors.ERROR_CODES);
  function constants(value: object) {
    for (const name of Object.keys(value)) {
      const child = (value as Record<string, unknown>)[name];
      words.add(name);
      if (typeof child === 'object' && child !== null && !Array.isArray(child)) constants(child);
    }
  }
  constants(config);
  constants(promptVersion);
  const source = (relative: string) => readFileSync(new URL(relative, import.meta.url), 'utf8');
  const env = ts.createSourceFile('env.ts', source('../env.ts'), ts.ScriptTarget.Latest, true);
  function visit(node: ts.Node) {
    if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      ['object', 'extend', 'pick'].includes(node.expression.name.text)
    ) {
      const shape = node.arguments[0];
      if (shape && ts.isObjectLiteralExpression(shape)) {
        for (const property of shape.properties) {
          if (
            property.name &&
            (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
            /^[A-Z][A-Z0-9_]*$/.test(property.name.text)
          )
            words.add(property.name.text);
        }
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(env);
  // Kit bootstrap also declares provider keys in requiredVariables().
  const kit = ts.createSourceFile(
    'config-files.ts',
    source('../cli/commands/config-files.ts'),
    ts.ScriptTarget.Latest,
    true,
  );
  function strings(node: ts.Node) {
    if (ts.isStringLiteral(node) && /^[A-Z][A-Z0-9_]*$/.test(node.text)) words.add(node.text);
    ts.forEachChild(node, strings);
  }
  for (const statement of kit.statements) {
    if (ts.isFunctionDeclaration(statement) && statement.name?.text === 'requiredVariables')
      strings(statement);
  }
  for (const name of Object.keys(parseEnv(source('../../.env.example')))) words.add(name);
  for (const text of [source('../../sourced'), source('../../scripts/docker-entrypoint.sh')]) {
    for (const match of text.matchAll(/^\s*(?:#\s*)?(?:export\s+)?([A-Z][A-Z0-9_]*)=/gm)) {
      if (match[1]) words.add(match[1]);
    }
  }
  return words;
}

export type Problem = { file: string; line: number; message: string };
export function checkSkill(
  file: string,
  content: string,
  folder: string,
  knownWords = knownSkillWords(),
): Problem[] {
  const problems: Problem[] = [];
  const add = (line: number, message: string) => problems.push({ file, line, message });
  const lines = content.split(/\r?\n/);
  const frontEnd = lines[0] === '---' ? lines.indexOf('---', 1) : -1;
  for (const key of ['name', 'description']) {
    const index = lines.findIndex(
      (line, i) => i > 0 && i < frontEnd && new RegExp(`^${key}:\\s*\\S`).test(line),
    );
    if (index < 0) add(1, `Missing front matter ${key}`);
    else if (
      key === 'name' &&
      lines[index]?.replace(/^name:\s*/, '').replace(/^['"]|['"]$/g, '') !== folder
    )
      add(index + 1, `Skill name must match folder ${folder}`);
  }
  for (const section of ['When to use', 'Before you start', 'Steps', 'Never', 'Done when']) {
    if (!lines.some((line) => new RegExp(`^#{1,6}\\s+${section}\\s*$`).test(line)))
      add(1, `Missing section ${section}`);
  }
  let context: Command | undefined;
  let fence: string | undefined;
  lines.forEach((line, index) => {
    const number = index + 1;
    const delimiter = /^\s{0,3}(`{3,}|~{3,})/.exec(line)?.[1];
    const inline = !fence && !delimiter;
    if (delimiter) {
      if (!fence) fence = delimiter;
      else if (delimiter[0] === fence[0] && delimiter.length >= fence.length) fence = undefined;
    }
    const marker = /^\s*<!-- sourced-command: (.+?) -->\s*$/.exec(line);
    if (marker) {
      context = names.find((name) => name === marker[1]);
      if (!context) add(number, `Unknown command ${marker[1] ?? ''}`);
      return;
    }
    // Quoted values are single tokens, so strings containing flags are not flags.
    for (const invocation of line.matchAll(/(?:\.\/sourced|pnpm\s+sourced)\s+([^`\n;&|]+)/g)) {
      const tokens = invocation[1]?.match(/"[^"]*"|'[^']*'|[^\s]+/g) ?? [];
      const name = names
        .slice()
        .sort((a, b) => b.length - a.length)
        .find((candidate) => candidate.split(' ').every((word, i) => tokens[i] === word));
      if (!name) {
        if (tokens[0] !== '--help') add(number, `Unknown command ${tokens[0] ?? '(missing)'}`);
        continue;
      }
      const flags = commands[name];
      const valid = new Set([
        ...globalFlags,
        ...(flags.boolean ?? []).map((f) => `--${f}`),
        ...(flags.string ?? []).map((f) => `--${f}`),
      ]);
      for (const token of tokens.slice(name.split(' ').length)) {
        if (token.startsWith('--') && !valid.has(token.split('=')[0] ?? token))
          add(number, `Unknown flag ${token.split('=')[0] ?? token} for ${name}`);
      }
    }
    const standaloneFlags = new Set([
      ...globalFlags,
      ...(context ? [commands[context]] : Object.values(commands)).flatMap((flags) =>
        [...(flags.boolean ?? []), ...(flags.string ?? [])].map((flag) => `--${flag}`),
      ),
    ]);
    // Match whole inline code spans, not flags embedded in other tools' commands.
    for (const span of line.matchAll(/(?<!`)(`+)([^`]*?)\1(?!`)/g)) {
      const flag = span[2]?.trim();
      if (inline && flag && /^--[a-z][\w-]*$/.test(flag) && !standaloneFlags.has(flag))
        add(number, `Unknown flag ${flag}${context ? ` for ${context}` : ''}`);
    }
    for (const match of line.matchAll(/\bresult(?:\.[A-Za-z_][\w]*(?:\[\]|\[key\])?)+/g)) {
      if (!context) add(number, `Result path ${match[0]} requires a sourced-command marker`);
      else if (!schemaFields(commandSchemas[context]).some((field) => field.path === match[0]))
        add(number, `Unknown result path ${match[0]} for ${context}`);
    }
    for (const match of line.matchAll(/\b[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+\b/g)) {
      if (!knownWords.has(match[0])) add(number, `Unknown error code ${match[0]}`);
    }
  });
  return problems;
}
async function entries(path: string) {
  try {
    return await readdir(path, { withFileTypes: true });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }
}
export async function checkSkills(root: string): Promise<Problem[]> {
  const knownWords = knownSkillWords();
  const problems: Problem[] = [];
  for (const folder of await entries(join(root, '.agents/skills'))) {
    if (!folder.isDirectory() || folder.name === '_shared') continue;
    const file = `.agents/skills/${folder.name}/SKILL.md`;
    try {
      problems.push(
        ...checkSkill(file, await readFile(join(root, file), 'utf8'), folder.name, knownWords),
      );
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
  }
  for (const entry of await entries(join(root, '.claude/commands'))) {
    if (!entry.isFile() || !entry.name.endsWith('.md')) continue;
    const file = `.claude/commands/${entry.name}`;
    const lines = (await readFile(join(root, file), 'utf8')).split(/\r?\n/);
    for (const [index, line] of lines.entries()) {
      for (const match of line.matchAll(/\.agents\/skills\/([\w-]+)(?:\/SKILL\.md)?/g)) {
        const folders = await entries(join(root, '.agents/skills'));
        if (!folders.some((folder) => folder.isDirectory() && folder.name === match[1]))
          problems.push({
            file,
            line: index + 1,
            message: `Missing skill folder ${match[1] ?? ''}`,
          });
      }
    }
  }
  let actual = '';
  try {
    actual = await readFile(join(root, referencePath), 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  const expected = generateReference();
  if (actual !== expected) {
    const lines = actual.split('\n');
    const first = expected.split('\n').findIndex((line, index) => lines[index] !== line);
    problems.push({
      file: referencePath,
      line: first < 0 ? expected.split('\n').length : first + 1,
      message: 'Stale CLI reference; run pnpm check-skills --write',
    });
  }
  return problems.sort((a, b) => a.file.localeCompare(b.file, 'en') || a.line - b.line);
}
